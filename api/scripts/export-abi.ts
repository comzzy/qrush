import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const artifactPath = resolve(import.meta.dirname, "../../contracts/out/QRushCheckout.sol/QRushCheckout.json");
const artifact = JSON.parse(readFileSync(artifactPath, "utf8")) as {
  abi: unknown;
  bytecode: { object: string };
};

const out = `// Generated by scripts/export-abi.ts from contracts/out. Do not edit.
export const qrushCheckoutAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;

export const qrushCheckoutBytecode = "${artifact.bytecode.object}" as const;
`;
writeFileSync(resolve(import.meta.dirname, "../src/contracts/artifact.ts"), out);
console.log("wrote src/contracts/artifact.ts");
